private final class MemoryCloud: DirectCloudTransport, @unchecked Sendable {
    private let lock = NSLock()
    private var storage: [String: Data] = [:]
    private var reads = 0
    var readCount: Int { lock.lock(); defer { lock.unlock() }; return reads }
    func read() throws -> [Data] { lock.lock(); defer { lock.unlock() }; reads += 1; return Array(storage.values) }
    func write(_ data: Data, account: String) throws { lock.lock(); defer { lock.unlock() }; storage[account] = data }
    func removeAll() throws { lock.lock(); defer { lock.unlock() }; storage = [:] }
}

@MainActor final class KeyAndCloudTests: XCTestCase {
    private func wait(_ cloud: DirectCloudSyncV1) async throws {
        for _ in 0..<500 { if !cloud.busy { return }; try await Task.sleep(for: .milliseconds(10)) }; XCTFail("Sync did not complete")
    }
    func testKeyCreationOpenSSHRoundTripAndImportBounds() throws {
        let created = TerminalSSHKey.create(), privateKey = try Curve25519.Signing.PrivateKey(rawRepresentation: created.seed)
        let imported = try TerminalSSHKey.importOpenSSH(privateKey.makeSSHRepresentation(), passphrase: "")
        XCTAssertEqual(imported.seed, created.seed); XCTAssertEqual(imported.publicKey, created.publicKey)
        XCTAssertTrue(created.fingerprint.hasPrefix("SHA256:"))
        XCTAssertThrowsError(try TerminalSSHKey.importOpenSSH("not a key", passphrase: ""))
        XCTAssertThrowsError(try TerminalSSHKey.importOpenSSH(String(repeating: "a", count: 32769), passphrase: ""))
        XCTAssertThrowsError(try TerminalSSHKey(seed: Data(repeating: 0, count: 31)).validate())
        let signature = try privateKey.signature(for: Data("synthetic SSH proof".utf8))
        XCTAssertTrue(privateKey.publicKey.isValidSignature(signature, for: Data("synthetic SSH proof".utf8)))
    }
    func testOpenSSHGeneratedEncryptedImportRejectsWrongPassphraseAndUnsupportedRSA() throws {
        // These keys are freshly generated by ssh-keygen outside the repository for this QA run.
        let bundle = Bundle(for: Self.self)
        let keyURL = try XCTUnwrap(bundle.url(forResource: "synthetic-ed25519", withExtension: nil))
        let text = try String(contentsOf: keyURL, encoding: .utf8)
        XCTAssertThrowsError(try TerminalSSHKey.importOpenSSH(text, passphrase: ""))
        XCTAssertThrowsError(try TerminalSSHKey.importOpenSSH(text, passphrase: "wrong"))
        let imported = try TerminalSSHKey.importOpenSSH(text, passphrase: "synthetic-import-only")
        let publicURL = try XCTUnwrap(bundle.url(forResource: "synthetic-ed25519", withExtension: "pub"))
        let expected = try String(contentsOf: publicURL, encoding: .utf8).split(separator: " ").prefix(2).joined(separator: " ")
        XCTAssertEqual(imported.publicKey, expected)
        let rsaURL = try XCTUnwrap(bundle.url(forResource: "synthetic-rsa", withExtension: nil))
        XCTAssertThrowsError(try TerminalSSHKey.importOpenSSH(String(contentsOf: rsaURL, encoding: .utf8), passphrase: ""))
    }
    func testStoredPrivateKeyIsDeviceOnlyAndAddressEditsKeepIt() throws {
        let id = UUID(), folder = URL.temporaryDirectory.appending(path: UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: folder); try? TerminalSecretStore.remove(id) }
        let library = DirectMacLibraryV1(url: folder.appending(path: "macs.json")), key = TerminalSSHKey.create()
        XCTAssertTrue(library.save(id: id, name: "Synthetic", address: "mac.local")); try TerminalSecretStore.saveKey(key, id: id)
        XCTAssertTrue(library.save(id: id, name: "Renamed", addresses: ["100.100.1.2", "mac.local"]))
        XCTAssertEqual(try TerminalSecretStore.sshKey(id)?.seed, key.seed)
        let query: [String: Any] = [kSecClass as String: kSecClassGenericPassword, kSecAttrService as String: "media.jenny.maccompanion.ssh-key-library-v2.v1", kSecAttrAccount as String: "00000000-0000-0000-0000-000000000002", kSecAttrSynchronizable as String: kSecAttrSynchronizableAny, kSecReturnAttributes as String: true]
        var result: CFTypeRef?; XCTAssertEqual(SecItemCopyMatching(query as CFDictionary, &result), errSecSuccess)
        let attributes = try XCTUnwrap(result as? [String: Any])
        XCTAssertEqual(attributes[kSecAttrAccessible as String] as? String, kSecAttrAccessibleWhenUnlockedThisDeviceOnly as String)
        XCTAssertFalse(attributes[kSecAttrSynchronizable as String] as? Bool ?? false)
    }
    func testIndexedCloudMergeTombstonesAndMalformedPayloadPreserveLocal() throws {
        let url = try XCTUnwrap(Bundle(for: Self.self).url(forResource: "direct-screen-sharing-v1", withExtension: "json"))
        let fixture = try XCTUnwrap(JSONSerialization.jsonObject(with: Data(contentsOf: url)) as? [String: Any])
        let additions = try XCTUnwrap(fixture["clientAdditions"] as? [String: Any]), policy = try XCTUnwrap(additions["cloudLibrary"] as? [String: Any])
        XCTAssertEqual(policy["defaultEnabled"] as? Bool, false); XCTAssertEqual(policy["secretsIncluded"] as? Bool, false)
        let mac = try DirectMacRecordV1.normalized(name: "Synthetic", address: "mac.local")
        for test in try XCTUnwrap(policy["mergeCases"] as? [[String: Any]]) {
            let local = DirectCloudVersion(id: mac.id, writer: UUID(), revision: Int64(try XCTUnwrap(test["localRevision"] as? Int)), mac: mac, preferences: .init(mac: mac.id))
            let deleted = test["remoteDeleted"] as? Bool == true
            let remote = DirectCloudVersion(id: mac.id, writer: UUID(), revision: Int64(try XCTUnwrap(test["remoteRevision"] as? Int)), mac: deleted ? nil : mac, preferences: deleted ? nil : .init(mac: mac.id))
            let winner = try XCTUnwrap(DirectCloudVersion.winners(DirectCloudVersion.merge([local], [remote]))[mac.id])
            XCTAssertEqual(winner, test["winner"] as? String == "local" ? local : remote)
            XCTAssertThrowsError(try DirectCloudVersion.merge([local], [remote, remote]))
            var corrupt = remote; corrupt.schema = 99; XCTAssertThrowsError(try DirectCloudVersion.merge([local], [corrupt]))
        }
    }
    func testSyncDefaultOffTwoDevicesDeletionAndNoCredentialTransport() async throws {
        let folder = URL.temporaryDirectory.appending(path: UUID().uuidString), transport = MemoryCloud(), id = UUID()
        let suiteA = UUID().uuidString, suiteB = UUID().uuidString
        let a = try XCTUnwrap(UserDefaults(suiteName: suiteA)), b = try XCTUnwrap(UserDefaults(suiteName: suiteB))
        defer { a.removePersistentDomain(forName: suiteA); b.removePersistentDomain(forName: suiteB); try? FileManager.default.removeItem(at: folder); try? TerminalSecretStore.remove(id); VNCSessionPreferences.clear(id) }
        let first = DirectMacLibraryV1(url: folder.appending(path: "a.json")), second = DirectMacLibraryV1(url: folder.appending(path: "b.json"))
        XCTAssertTrue(first.save(id: id, name: "Synthetic Mac", address: "mac.local"))
        let cloudA = DirectCloudSyncV1(defaults: a, url: folder.appending(path: "journal-a.json"), transport: transport, writerID: UUID())
        let cloudB = DirectCloudSyncV1(defaults: b, url: folder.appending(path: "journal-b.json"), transport: transport, writerID: UUID())
        cloudA.attach(first); cloudB.attach(second)
        XCTAssertFalse(cloudA.enabled); XCTAssertEqual(transport.readCount, 0)
        let key = TerminalSSHKey.create(); try TerminalSecretStore.saveKey(key, id: id)
        try TerminalSecretStore.save(.init(username: "MUST-NOT-SYNC", password: "MUST-NOT-SYNC"), id: id)
        cloudA.setEnabled(true); try await wait(cloudA); cloudB.setEnabled(true); try await wait(cloudB)
        XCTAssertEqual(second.macs.first?.id, id); XCTAssertEqual(second.macs.first?.addresses, ["mac.local"])
        for data in try transport.read() { let text = String(decoding: data, as: UTF8.self); XCTAssertFalse(text.contains("MUST-NOT-SYNC")); XCTAssertFalse(text.contains(key.seed.base64EncodedString())); XCTAssertFalse(text.contains("username")); XCTAssertFalse(text.contains("host-key")) }
        cloudA.setEnabled(false); let before = transport.readCount
        XCTAssertTrue(first.save(id: id, name: "Offline edit", addresses: ["100.100.1.2"])); cloudA.refresh()
        XCTAssertEqual(transport.readCount, before); XCTAssertEqual(first.macs.first?.name, "Offline edit")
        cloudA.setEnabled(true); try await wait(cloudA); cloudB.refresh(); try await wait(cloudB)
        XCTAssertEqual(second.macs.first?.name, "Offline edit")
        // Remote removal drops the Mac, but does not delete the recipient's device-only key.
        second.remove(try XCTUnwrap(second.macs.first)); try await wait(cloudB)
        try TerminalSecretStore.saveKey(key, id: id)
        cloudA.refresh(); try await wait(cloudA); XCTAssertTrue(first.macs.isEmpty); XCTAssertEqual(try TerminalSecretStore.sshKey(id)?.seed, key.seed)
        cloudA.setEnabled(false); cloudB.setEnabled(false)
    }
    func testActualSynchronizableKeychainTransportRoundTripAndDelete() throws {
        let transport = DirectCloudKeychain(service: "media.jenny.maccompanion.synthetic-cloud-qa." + UUID().uuidString)
        defer { try? transport.removeAll() }
        let bytes = Data("synthetic-only".utf8)
        XCTAssertTrue(try transport.read().isEmpty)
        try transport.write(bytes, account: "synthetic")
        XCTAssertEqual(try transport.read(), [bytes])
        try transport.write(Data("updated-synthetic".utf8), account: "synthetic")
        XCTAssertEqual(try transport.read(), [Data("updated-synthetic".utf8)])
        try transport.removeAll(); XCTAssertTrue(try transport.read().isEmpty)
    }
    func testCorruptCloudDataKeepsReadableLocalLibrary() async throws {
        let folder = URL.temporaryDirectory.appending(path: UUID().uuidString), transport = MemoryCloud(), suite = UUID().uuidString
        let defaults = try XCTUnwrap(UserDefaults(suiteName: suite))
        defer { defaults.removePersistentDomain(forName: suite); try? FileManager.default.removeItem(at: folder) }
        let library = DirectMacLibraryV1(url: folder.appending(path: "macs.json"))
        XCTAssertTrue(library.save(id: nil, name: "Preserved", address: "mac.local")); let before = library.macs
        try transport.write(Data("corrupt".utf8), account: "synthetic-corrupt")
        let cloud = DirectCloudSyncV1(defaults: defaults, url: folder.appending(path: "journal.json"), transport: transport, writerID: UUID())
        cloud.attach(library); cloud.setEnabled(true); try await wait(cloud)
        XCTAssertEqual(library.macs, before); XCTAssertEqual(cloud.recovery?.reason, .cloudUnavailable); cloud.setEnabled(false)
    }
}
